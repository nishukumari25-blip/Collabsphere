import React, { useState, useEffect } from 'react';
import ReactMarkdown from 'react-markdown';
import {
  FileText,
  Sparkles,
  Download,
  Copy,
  Check,
  AlertCircle
} from 'lucide-react';
import { geminiService } from '../../services/geminiService';
import { useProject } from '../../context/ProjectContext';
import { useToast } from '../../context/ToastContext';

export const AIReadmeGeneratorPage = () => {
  const { currentProject } = useProject();
  const toast = useToast();

  const [formData, setFormData] = useState({
    projectName: currentProject?.name || 'CollabSphere',
    description: currentProject?.description || 'Enterprise AI-powered developer collaboration platform featuring Markdown documentation, secure file storage, and Gemini 2.5 SDK integration.',
    technologies: currentProject?.technologies?.join(', ') || 'React, Vite, Node.js, Express, MongoDB, Mongoose, @google/genai, Multer',
    features: 'JWT authentication with HttpOnly cookies; Role-based project access control (OWNER, ADMIN, MEMBER, VIEWER); Live Markdown notes workspace; Authenticated code and image file preview; Gemini AI Code Explainer and Technical Docs Generator; Real MongoDB activity analytics and timeline; Public read-only project sharing links',
    installation: 'git clone <repo>\ncd collabsphere\nnpm run install:all\n# Configure server/.env with MONGODB_URI and GEMINI_API_KEY\nnpm run dev',
    usage: 'Navigate to http://localhost:5173 to access the developer dashboard and Gemini AI Studio.'
  });

  const [readme, setReadme] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    if (currentProject) {
      setFormData((prev) => ({
        ...prev,
        projectName: currentProject.name || prev.projectName,
        description: currentProject.description || prev.description,
        technologies: currentProject.technologies?.length ? currentProject.technologies.join(', ') : prev.technologies
      }));
    }
  }, [currentProject]);

  const handleChange = (e) => {
    setFormData({ ...formData, [e.target.name]: e.target.value });
  };

  const handleGenerate = async (e) => {
    e.preventDefault();
    if (!formData.projectName.trim() || !formData.description.trim()) {
      toast.warning('Project name and description are required');
      return;
    }

    setLoading(true);
    setError('');
    setReadme('');

    try {
      const res = await geminiService.generateReadme({
        ...formData,
        technologies: formData.technologies.split(',').map((t) => t.trim()).filter(Boolean),
        features: formData.features.split(';').map((f) => f.trim()).filter(Boolean),
        projectId: currentProject?._id
      });
      if (res.success && res.result) {
        setReadme(res.result);
        toast.success('Professional README.md generated by Gemini AI');
      }
    } catch (err) {
      setError(err.message || 'Failed to generate README');
      toast.error(err.message);
    } finally {
      setLoading(false);
    }
  };

  const handleCopy = () => {
    if (!readme) return;
    navigator.clipboard.writeText(readme);
    setCopied(true);
    toast.success('README markdown copied to clipboard');
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    if (!readme) return;
    const blob = new Blob([readme], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.setAttribute('download', 'README.md');
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    toast.success('README.md downloaded successfully');
  };

  return (
    <div>
      <div className="page-header">
        <div>
          <h1 className="page-title">AI README Generator</h1>
          <p className="page-subtitle">
            Craft beautiful, comprehensive, production-ready README.md files for GitHub repositories using Gemini AI.
          </p>
        </div>
      </div>

      <div style={{ display: 'grid', gridTemplateColumns: '1.1fr 1.3fr', gap: '2rem', alignItems: 'flex-start' }}>
        {/* Left: Input Specification Form */}
        <div className="card" style={{ padding: '1.75rem' }}>
          <form onSubmit={handleGenerate}>
            <div className="form-group">
              <label className="form-label">Project Name *</label>
              <input
                type="text"
                name="projectName"
                required
                className="form-input"
                value={formData.projectName}
                onChange={handleChange}
              />
            </div>

            <div className="form-group">
              <label className="form-label">Project Description *</label>
              <textarea
                name="description"
                rows={3}
                required
                className="form-textarea"
                value={formData.description}
                onChange={handleChange}
              />
            </div>

            <div className="form-group">
              <label className="form-label">Technologies (comma-separated)</label>
              <input
                type="text"
                name="technologies"
                className="form-input"
                value={formData.technologies}
                onChange={handleChange}
              />
            </div>

            <div className="form-group">
              <label className="form-label">Key Features (semicolon-separated)</label>
              <textarea
                name="features"
                rows={4}
                className="form-textarea"
                value={formData.features}
                onChange={handleChange}
              />
            </div>

            <div className="form-group">
              <label className="form-label">Installation Instructions</label>
              <textarea
                name="installation"
                rows={3}
                className="form-textarea"
                style={{ fontFamily: 'var(--font-mono)', fontSize: '0.85rem' }}
                value={formData.installation}
                onChange={handleChange}
              />
            </div>

            <div className="form-group">
              <label className="form-label">Usage Notes</label>
              <textarea
                name="usage"
                rows={2}
                className="form-textarea"
                value={formData.usage}
                onChange={handleChange}
              />
            </div>

            <button
              type="submit"
              className="btn btn-primary"
              disabled={loading}
              style={{ width: '100%', marginTop: '0.5rem' }}
            >
              <Sparkles size={16} />
              <span>{loading ? 'Gemini Crafting README.md...' : 'Generate Professional README'}</span>
            </button>
          </form>
        </div>

        {/* Right: Generated Markdown & Actions */}
        <div className="card" style={{ padding: '1.75rem', minHeight: '600px' }}>
          <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: '1.25rem', borderBottom: '1px solid var(--border-light)', paddingBottom: '0.75rem' }}>
            <span style={{ fontWeight: 700, fontSize: '1rem' }}>README.md Live Preview</span>
            {readme && (
              <div style={{ display: 'flex', gap: '0.5rem' }}>
                <button onClick={handleCopy} className="btn btn-secondary btn-sm">
                  {copied ? <Check size={14} color="var(--success)" /> : <Copy size={14} />}
                  <span>{copied ? 'Copied' : 'Copy'}</span>
                </button>
                <button onClick={handleDownload} className="btn btn-secondary btn-sm">
                  <Download size={14} />
                  <span>Download .md</span>
                </button>
              </div>
            )}
          </div>

          {error && (
            <div
              style={{
                padding: '0.85rem 1rem',
                backgroundColor: 'var(--danger-bg)',
                border: '1px solid var(--danger-border)',
                borderRadius: 'var(--radius-sm)',
                color: 'var(--danger)',
                fontSize: '0.85rem',
                display: 'flex',
                alignItems: 'center',
                gap: '0.5rem'
              }}
            >
              <AlertCircle size={18} />
              <span>{error}</span>
            </div>
          )}

          {loading ? (
            <div style={{ textAlign: 'center', padding: '5rem 1rem' }}>
              <div className="skeleton" style={{ width: '56px', height: '56px', borderRadius: '50%', margin: '0 auto 1.5rem' }} />
              <h3 style={{ fontSize: '1.1rem', fontWeight: 700, color: 'var(--text-main)', marginBottom: '0.4rem' }}>
                Synthesizing README structure...
              </h3>
              <p style={{ color: 'var(--text-muted)', fontSize: '0.85rem' }}>
                Formatting badges, setup scripts, feature matrices, and architecture guides.
              </p>
            </div>
          ) : readme ? (
            <div className="markdown-body" style={{ maxHeight: '680px', overflowY: 'auto', paddingRight: '0.5rem' }}>
              <ReactMarkdown>{readme}</ReactMarkdown>
            </div>
          ) : !error ? (
            <div style={{ textAlign: 'center', padding: '6rem 1rem', color: 'var(--text-muted)' }}>
              <FileText size={42} color="var(--border-subtle)" style={{ marginBottom: '1rem' }} />
              <p style={{ fontSize: '0.9rem' }}>
                Fill in the details on the left and click <strong>"Generate Professional README"</strong>.
              </p>
            </div>
          ) : null}
        </div>
      </div>
    </div>
  );
};
